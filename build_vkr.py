def set_default_font(doc, font_name='Times New Roman', size=14):
    style = doc.styles['Normal']
    style.font.name = font_name
    style.font.size = Pt(size)
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.insert(0, rfonts)
    rfonts.set(qn('w:ascii'), font_name)
    rfonts.set(qn('w:hAnsi'), font_name)
    rfonts.set(qn('w:cs'), font_name)
    rfonts.set(qn('w:eastAsia'), font_name)


def set_page_margins(section, left=30, top=20, right=10, bottom=20):
    section.left_margin = Mm(left)
    section.top_margin = Mm(top)
    section.right_margin = Mm(right)
    section.bottom_margin = Mm(bottom)
    section.page_height = Mm(297)
    section.page_width = Mm(210)


def _set_run_font(run, name='Times New Roman', size=14, bold=False, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.insert(0, rfonts)
    rfonts.set(qn('w:ascii'), name)
    rfonts.set(qn('w:hAnsi'), name)
    rfonts.set(qn('w:cs'), name)


def add_paragraph(doc_or_cell, text='', alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                  bold=False, italic=False, size=14, indent_first=True,
                  line_spacing=1.5, space_before=0, space_after=0,
                  font_name='Times New Roman', left_indent=0):
    p = doc_or_cell.add_paragraph()
    p.alignment = alignment
    pf = p.paragraph_format
    pf.line_spacing = line_spacing
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.first_line_indent = Mm(12.5) if indent_first else Mm(0)
    if left_indent:
        pf.left_indent = Mm(left_indent)
    if text:
        run = p.add_run(text)
        _set_run_font(run, font_name, size, bold, italic)
    return p


def add_centered(doc, text, bold=False, italic=False, size=14, line_spacing=1.0,
                 space_before=0, space_after=0):
    return add_paragraph(doc, text, alignment=WD_ALIGN_PARAGRAPH.CENTER,
                         bold=bold, italic=italic, size=size, indent_first=False,
                         line_spacing=line_spacing,
                         space_before=space_before, space_after=space_after)


def add_blank(doc, size=14):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.first_line_indent = Mm(0)
    run = p.add_run('')
    _set_run_font(run, size=size)
    return p


def add_page_number_footer(section):
    """Номера страниц по центру снизу. Первая страница без номера."""
    section.different_first_page_header_footer = True
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Mm(0)
    run = p.add_run()
    _set_run_font(run, size=14)
    fld_begin = OxmlElement('w:fldChar')
    fld_begin.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.text = 'PAGE   \\* MERGEFORMAT'
    fld_sep = OxmlElement('w:fldChar')
    fld_sep.set(qn('w:fldCharType'), 'separate')
    fld_end = OxmlElement('w:fldChar')
    fld_end.set(qn('w:fldCharType'), 'end')
    run._r.append(fld_begin); run._r.append(instr); run._r.append(fld_sep); run._r.append(fld_end)


def add_heading_struct(doc, text):
    """Заголовок структурного элемента (РЕФЕРАТ, СОДЕРЖАНИЕ, ВВЕДЕНИЕ ...).
    Прописными, по центру, полужирно, без подчёркивания, без точки. СТУ 6.1."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_after = Pt(14)
    pf.first_line_indent = Mm(0)
    run = p.add_run(text)
    _set_run_font(run, size=14, bold=True)
    return p


def add_heading_section(doc, num, title, level=1):
    """Заголовок раздела/подраздела. С абзацного отступа, прописная первая буква,
    полужирно, без точки в конце, не подчёркивая. СТУ 7.5.3."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    if level == 1:
        pf.space_before = Pt(14)
        pf.space_after = Pt(14)
    else:
        pf.space_before = Pt(8)
        pf.space_after = Pt(8)
    pf.first_line_indent = Mm(12.5)
    run = p.add_run(f'{num} {title}')
    _set_run_font(run, size=14, bold=True)
    # Запретить разрыв страницы перед/после заголовка
    keep_with_next = OxmlElement('w:keepNext'); keep_with_next.set(qn('w:val'), '1')
    p._p.get_or_add_pPr().append(keep_with_next)
    return p


def add_toc_entry(doc, num, title, page, level=0):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.first_line_indent = Mm(0)
    if level == 1:
        pf.left_indent = Mm(7.5)
    elif level == 2:
        pf.left_indent = Mm(15)
    pf.tab_stops.add_tab_stop(Mm(170), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
    run = p.add_run(f'{num} {title}' if num else title)
    _set_run_font(run, size=14)
    tab_run = p.add_run('\t' + str(page))
    _set_run_font(tab_run, size=14)
    return p


def remove_cell_borders(cell):
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    for b in ['top', 'left', 'bottom', 'right']:
        border = OxmlElement(f'w:{b}')
        border.set(qn('w:val'), 'nil')
        tcBorders.append(border)
    tcPr.append(tcBorders)


def set_cell_text(cell, text, size=14, bold=False, italic=False,
                  alignment=WD_ALIGN_PARAGRAPH.LEFT, line_spacing=1.0):
    cell.text = ''
    p = cell.paragraphs[0]
    p.alignment = alignment
    p.paragraph_format.first_line_indent = Mm(0)
    p.paragraph_format.line_spacing = line_spacing
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    run = p.add_run(text)
    _set_run_font(run, size=size, bold=bold, italic=italic)


def set_cell_width(cell, width_mm):
    cell.width = Mm(width_mm)
    tcPr = cell._tc.get_or_add_tcPr()
    tcW = tcPr.find(qn('w:tcW'))
    if tcW is None:
        tcW = OxmlElement('w:tcW')
        tcPr.append(tcW)
    tcW.set(qn('w:type'), 'dxa')
    tcW.set(qn('w:w'), str(int(width_mm * 56.7)))  # mm -> twips


def add_figure_placeholder(doc, fig_num, caption, height_mm=85):
    """Место под рисунок: рамка с серой границей и подпись по СТУ 7.8.
    Подпись: «Рисунок N.M — Название» по центру под рисунком."""
    # Сама «рамка»
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    cell = table.rows[0].cells[0]
    set_cell_width(cell, 160)  # ширина рамки 160 мм
    set_cell_text(cell, f'[ место для рисунка {fig_num} ]',
                  size=12, italic=True,
                  alignment=WD_ALIGN_PARAGRAPH.CENTER, line_spacing=1.0)
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER

    # Высота строки в твипах (1 мм ≈ 56.7 твипов)
    tr = cell._tc.getparent()
    trPr = tr.get_or_add_trPr()
    height = OxmlElement('w:trHeight')
    height.set(qn('w:val'), str(int(height_mm * 56.7)))
    height.set(qn('w:hRule'), 'atLeast')
    trPr.append(height)

    # Серая рамка вокруг места для рисунка
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    for side in ['top', 'left', 'bottom', 'right']:
        b = OxmlElement(f'w:{side}')
        b.set(qn('w:val'), 'single')
        b.set(qn('w:sz'), '6')
        b.set(qn('w:color'), '808080')
        tcBorders.append(b)
    tcPr.append(tcBorders)

    # Подпись по центру: «Рисунок N — Название»
    add_centered(doc, f'Рисунок {fig_num} — {caption}',
                 size=14, line_spacing=1.5, space_before=6, space_after=10)


def add_paragraphs(doc, paragraphs):
    """Шорткат для серии абзацев одинакового стиля."""
    for p in paragraphs:
        add_paragraph(doc, p)


def add_data_table(doc, title, headers, rows, col_widths_mm=None):
    """Таблица по СТУ 7.7: заголовок слева без отступа, формат «Таблица N - Название».
    Границы только справа, слева, снизу. Шапка отделена двойной линией."""
    # Заголовок таблицы
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.first_line_indent = Mm(0)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(4)
    run = p.add_run(title)
    _set_run_font(run, size=14)

    # Сама таблица
    cols = len(headers)
    table = doc.add_table(rows=1 + len(rows), cols=cols)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False

    # Применяем границы
    for row_idx, row in enumerate(table.rows):
        for col_idx, cell in enumerate(row.cells):
            tcPr = cell._tc.get_or_add_tcPr()
            tcBorders = OxmlElement('w:tcBorders')
            # СТУ 7.7.4: справа, слева, снизу - линии. Шапка отделена двойной линией.
            for side in ['top', 'left', 'bottom', 'right']:
                border = OxmlElement(f'w:{side}')
                if row_idx == 0 and side == 'bottom':
                    border.set(qn('w:val'), 'double')
                    border.set(qn('w:sz'), '4')
                else:
                    border.set(qn('w:val'), 'single')
                    border.set(qn('w:sz'), '4')
                border.set(qn('w:color'), '000000')
                tcBorders.append(border)
            tcPr.append(tcBorders)
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER

    # Шапка
    for i, h in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], h, size=12, bold=True,
                      alignment=WD_ALIGN_PARAGRAPH.CENTER, line_spacing=1.15)
        if col_widths_mm and i < len(col_widths_mm):
            set_cell_width(table.rows[0].cells[i], col_widths_mm[i])

    # Данные
    for r_idx, row_data in enumerate(rows):
        for c_idx, val in enumerate(row_data):
            cell = table.rows[r_idx + 1].cells[c_idx]
            # Жирный для последней строки (если она содержит «Разрабатываемая»)
            bold = isinstance(val, str) and 'Разрабатываемая' in val
            set_cell_text(cell, str(val), size=11, bold=bold,
                          alignment=WD_ALIGN_PARAGRAPH.LEFT, line_spacing=1.15)
            if col_widths_mm and c_idx < len(col_widths_mm):
                set_cell_width(cell, col_widths_mm[c_idx])

    return table


